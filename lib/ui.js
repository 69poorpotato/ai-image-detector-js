/**
 * Terminal dashboard and report renderer for Node.js using picocolors.
 * Clean, compact, 84-column layout with zero emojis.
 */

const pc = require('picocolors');

function renderBanner() {
  console.log(pc.cyan('=================================================================================='));
  console.log(pc.bold('   AI IMAGE DETECTOR (JS)  v1.0   *   Content Credentials & Forensics Suite'));
  console.log(pc.cyan('=================================================================================='));
}

function renderReport(report, verbose = false) {
  renderBanner();
  renderVerdictCard(report);

  if (report.c2pa && report.c2pa.hasC2PA) {
    renderProvenanceCard(report);
  }

  if (report.metadata && (report.metadata.hasAIMetadata || report.metadata.hasCameraExif)) {
    renderMetadataCard(report);
  }

  if (report.forensics) {
    renderForensicsCard(report, verbose);
  }

  renderFooter();
}

function renderVerdictCard(report) {
  const { fileInfo, verdict, confidence } = report;

  let badge = pc.bgWhite(pc.black('  INCONCLUSIVE  '));
  let statusText = pc.dim('Metadata absent, forensic signals ambiguous');
  let borderColor = pc.blue;

  if (verdict.includes('CONFIRMED') || verdict.includes('HIGH')) {
    badge = pc.bgRed(pc.bold(pc.white('  AI GENERATED (CONFIRMED)  ')));
    statusText = pc.bold(pc.red('Confirmed AI-Generated Media'));
    borderColor = pc.red;
  } else if (verdict.includes('SUSPICIOUS')) {
    badge = pc.bgYellow(pc.bold(pc.black('  SUSPICIOUS / LIKELY AI  ')));
    statusText = pc.bold(pc.yellow('Irregular synthetic signals found'));
    borderColor = pc.yellow;
  } else if (verdict.includes('AUTHENTIC')) {
    badge = pc.bgGreen(pc.bold(pc.white('  AUTHENTIC PHOTO  ')));
    statusText = pc.bold(pc.green('Authentic camera capture'));
    borderColor = pc.green;
  }

  const barLen = 20;
  const filled = Math.max(0, Math.min(barLen, Math.floor((confidence / 100) * barLen)));
  const progBar = '#'.repeat(filled) + '-'.repeat(barLen - filled);

  console.log(borderColor('+------------------------------- VERDICT & SUMMARY --------------------------------+'));
  console.log(`|     Target File:  ${pc.bold(fileInfo.fileName)} ${pc.dim(`(${fileInfo.dimensions} · ${fileInfo.format} · ${fileInfo.fileSizeHuman})`)}`);
  console.log(`|         Verdict:  ${badge}  ${statusText}`);
  console.log(`|      Confidence:  ${pc.bold(pc.yellow(`${confidence.toFixed(1)}%`))} ${borderColor(`[${progBar}]`)}`);
  if (report.detectedGenerator) {
    console.log(`|    Generated By:  ${pc.bold(pc.magenta(report.detectedGenerator))}`);
  }
  console.log(`|  Primary Reason:  ${report.primaryIndicator}`);
  console.log(borderColor('+----------------------------------------------------------------------------------+'));
}

function renderProvenanceCard(report) {
  const c = report.c2pa;
  console.log(pc.magenta('+---------------------- ORIGIN & CONTENT CREDENTIALS (C2PA) -----------------------+'));
  if (c.claimGenerator) console.log(`|      Media Engine:  ${c.claimGenerator}`);
  if (c.issuer) console.log(`|  Signed Authority:  ${pc.bold(c.issuer)} ${pc.dim(`(${c.commonName || ''})`)}`);
  if (c.signatureTime) console.log(`|      Created Time:  ${c.signatureTime}`);

  for (const act of c.actions || []) {
    const sw = `${act.softwareName || ''} ${act.softwareVersion || ''}`.trim();
    let desc = `${pc.bold(act.action)}`;
    if (sw) desc += ` via ${pc.cyan(sw)}`;
    if (act.digitalSourceLabel) desc += ` -> ${pc.yellow(act.digitalSourceLabel)}`;
    console.log(`|      Audit Action:  ${desc}`);
  }

  if (c.watermarks && c.watermarks.length > 0) {
    console.log(`|        Watermarks:  ${pc.yellow(c.watermarks.join(', '))} ${pc.dim('(Cryptographic watermark detected)')}`);
  }
  console.log(pc.magenta('+----------------------------------------------------------------------------------+'));
}

function renderMetadataCard(report) {
  const m = report.metadata;
  console.log(pc.green('+----------------------- EXTRACTED GENERATION METADATA ----------------------------+'));
  if (m.detectedGenerator) console.log(`|    Generator Tool:  ${pc.bold(pc.cyan(m.detectedGenerator))}`);
  if (m.prompt) console.log(`|            Prompt:  "${pc.italic(m.prompt.slice(0, 70))}"`);
  if (m.negativePrompt) console.log(`|   Negative Prompt:  "${pc.dim(m.negativePrompt.slice(0, 70))}"`);
  if (m.model) console.log(`|             Model:  ${m.model}`);

  const params = [];
  if (m.steps) params.push(`Steps: ${m.steps}`);
  if (m.sampler) params.push(`Sampler: ${m.sampler}`);
  if (m.cfgScale) params.push(`CFG: ${m.cfgScale}`);
  if (m.seed !== null) params.push(`Seed: ${m.seed}`);
  if (params.length > 0) console.log(`|          Settings:  ${params.join(' · ')}`);

  if (m.hasCameraExif) {
    console.log(`|   Camera Hardware:  ${pc.bold(`${m.cameraMake || ''} ${m.cameraModel || ''}`)}`);
  }
  console.log(pc.green('+----------------------------------------------------------------------------------+'));
}

function renderForensicsCard(report, verbose = false) {
  const f = report.forensics;
  const fScore = Math.floor(f.forensicScore * 100);
  const scoreCol = fScore >= 60 ? pc.red : (fScore >= 35 ? pc.yellow : pc.green);

  console.log(pc.cyan(`+-------------------- PIXEL & SIGNAL FORENSICS (Anomaly: ${scoreCol(`${fScore}%`)}) ---------------------+`));
  console.log('|');
  console.log('|    Forensic Check        Status                 Plain English Explanation');
  console.log('|  ------------------------------------------------------------------------------');

  // Texture
  const textureStatus = f.smoothnessRatio > 0.35 ? pc.bold(pc.red('Synthetic Smoothing')) : pc.green('Natural Detail');
  const textureExp = f.smoothnessRatio > 0.35 ? 'Severe lack of natural micro-tex' : 'Natural micro-texture present';
  console.log(`|    Texture & Skin        ${pad(textureStatus, 23)} ${textureExp}`);

  // Noise
  const noiseStatus = f.noiseKurtosis > 20 ? pc.bold(pc.red('Heavy-Tail Anomaly ')) : pc.green('Natural Sensor Noise');
  const noiseExp = f.noiseKurtosis > 20 ? 'Non-sensor noise (diffusion)    ' : 'Conforms to sensor Gaussian';
  console.log(`|    Noise Distribution    ${pad(noiseStatus, 23)} ${noiseExp}`);

  // Frequency
  const freqStatus = f.psdSlope < -2.9 ? pc.bold(pc.red('Abnormal Rolloff   ')) : pc.green('Natural Power-Law   ');
  const freqExp = f.psdSlope < -2.9 ? 'High-frequency decay is steep   ' : 'Conforms to 1/f^2 physics';
  console.log(`|    Frequency Spectrum    ${pad(freqStatus, 23)} ${freqExp}`);

  // Grid
  const gridStatus = f.spectralGridScore > 7 ? pc.bold(pc.red('Grid Artifacts Flagged')) : pc.green('Clean Spectrum        ');
  const gridExp = f.spectralGridScore > 7 ? 'Periodic upscaler/grid traces   ' : 'No periodic deconvolution';
  console.log(`|    Neural Grid Check     ${pad(gridStatus, 23)} ${gridExp}`);

  if (verbose) {
    console.log(`|    [Verbose Math]        Kurtosis: ${f.noiseKurtosis} · Slope: ${f.psdSlope} · PeakScore: ${f.spectralGridScore}`);
  }

  console.log('|');
  console.log(pc.cyan('+----------------------------------------------------------------------------------+'));
}

function renderFooter() {
  console.log(`  ${pc.dim('[Tip] Export standalone HTML report via')} ${pc.bold(pc.cyan('--html report.html'))}\n`);
}

function pad(str, len) {
  // Strip ANSI length estimation
  const clean = str.replace(/\x1b\[[0-9;]*m/g, '');
  const diff = len - clean.length;
  return diff > 0 ? str + ' '.repeat(diff) : str;
}

module.exports = { renderBanner, renderReport };
